-- PostgreSQL queue mirrors the MySQL layout and encryption contract.
CREATE TABLE IF NOT EXISTS telemetry_inbox (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_id BIGINT NOT NULL,
    elder_id BIGINT NOT NULL,
    binding_epoch BIGINT NOT NULL,
    request_id VARCHAR(64) NOT NULL,
    payload TEXT NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'pending',
    attempts INTEGER NOT NULL DEFAULT 0,
    next_retry_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    completed_at TIMESTAMPTZ,
    last_error VARCHAR(500),
    CONSTRAINT uq_telemetry_inbox_request UNIQUE(device_id,request_id)
);
CREATE INDEX IF NOT EXISTS idx_telemetry_inbox_pending ON telemetry_inbox(status,next_retry_at,id);
CREATE TABLE IF NOT EXISTS telemetry_inbox_guard (
    id SMALLINT PRIMARY KEY
);
INSERT INTO telemetry_inbox_guard(id) VALUES(1) ON CONFLICT (id) DO NOTHING;
