-- 0005: Durable care incidents and delivery attempts.
-- An SOS acknowledged by HTTP is only RECEIVED; it is not a confirmed delivery
-- or a human acknowledgement. These states deliberately remain separate.
CREATE TABLE IF NOT EXISTS care_incident (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source_alarm_id integer REFERENCES alarm_precess(id) ON DELETE SET NULL,
  old_id integer NOT NULL,
  device_id integer NOT NULL,
  kind varchar(32) NOT NULL DEFAULT 'sos',
  state varchar(32) NOT NULL DEFAULT 'received'
    CHECK (state IN ('received','notifying','notified','acknowledged','in_progress','resolved','verified','escalated')),
  severity varchar(16) NOT NULL DEFAULT 'critical',
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  acknowledged_by varchar(128),
  acknowledged_at timestamptz,
  resolved_by varchar(128),
  resolved_at timestamptz,
  resolution_note text,
  verified_by varchar(128),
  verified_at timestamptz,
  due_at timestamptz NOT NULL DEFAULT (now() + interval '5 minutes')
);
CREATE INDEX IF NOT EXISTS idx_care_incident_open_due
  ON care_incident (due_at, created_at)
  WHERE state NOT IN ('verified');

CREATE TABLE IF NOT EXISTS care_incident_event (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  incident_id bigint NOT NULL REFERENCES care_incident(id) ON DELETE RESTRICT,
  actor varchar(128) NOT NULL,
  action varchar(40) NOT NULL,
  note text,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_care_incident_event_incident
  ON care_incident_event (incident_id, created_at);

CREATE TABLE IF NOT EXISTS care_notification_outbox (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  incident_id bigint NOT NULL REFERENCES care_incident(id) ON DELETE RESTRICT,
  channel varchar(20) NOT NULL,
  recipient varchar(128) NOT NULL,
  status varchar(20) NOT NULL DEFAULT 'pending'
    CHECK (status IN ('pending','sending','sent','delivered','failed')),
  attempts integer NOT NULL DEFAULT 0,
  retry_at timestamptz NOT NULL DEFAULT now(),
  sent_at timestamptz,
  delivered_at timestamptz,
  last_error text,
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (incident_id, channel, recipient)
);
CREATE INDEX IF NOT EXISTS idx_care_notification_retry ON care_notification_outbox (retry_at, id)
  WHERE status IN ('pending','failed');
