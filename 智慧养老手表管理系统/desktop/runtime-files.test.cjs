const { test } = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')
const { appendLog, removeDiscovery } = require('./runtime-files.cjs')

test('logs rotate with two retained files and bounded writes', t => {
  const folder = fs.mkdtempSync(path.join(os.tmpdir(), 'suining-log-test-'))
  t.after(() => { for (const name of fs.readdirSync(folder)) fs.unlinkSync(path.join(folder, name)); fs.rmdirSync(folder) })
  const file = path.join(folder, 'startup-error.log')
  for (let i = 0; i < 8; i++) appendLog(file, String(i).repeat(20), 32)
  assert.deepEqual(fs.readdirSync(folder).sort(), ['startup-error.log', 'startup-error.log.1', 'startup-error.log.2'])
  assert.equal(fs.readFileSync(file, 'utf8'), '7'.repeat(20))
  assert.equal(fs.readFileSync(file + '.2', 'utf8'), '5'.repeat(20))
  appendLog(file, Buffer.from('x'.repeat(64)), 32)
  assert.equal(fs.statSync(file).size, 32)
})
test('shutdown removes only its own port discovery record', t => {
  const folder = fs.mkdtempSync(path.join(os.tmpdir(), 'suining-port-test-'))
  t.after(() => fs.rmdirSync(folder))
  const file = path.join(folder, 'server.json')
  fs.writeFileSync(file, JSON.stringify({ pid: 123 }))
  removeDiscovery(file, 456)
  assert.ok(fs.existsSync(file))
  removeDiscovery(file, 123)
  assert.ok(!fs.existsSync(file))
  assert.doesNotThrow(() => removeDiscovery(file, 123))
})
